export const cabinetRoleKey = (role: CabinetRole): string => ROLE_KEYS[role];
export const cabinetMemberStatusKey = (status: CabinetMemberStatus): string =>
  MEMBER_STATUS_KEYS[status];
export const cabinetInvitationStatusKey = (status: CabinetInvitationStatus): string =>
  INVITATION_STATUS_KEYS[status];

export function cabinetTeamErrorKey(error: unknown, fallback: string): string {
  const code = backendErrorCode(error);
  return (code && ERROR_KEYS[code]) || fallback;
}

export function backendErrorCode(error: unknown): string | null {
  if (!(error instanceof HttpErrorResponse) || !error.error || typeof error.error !== 'object') {
    return null;
  }
  const body = error.error as {
    message?: string | { code?: string };
    error?: { code?: string };
  };
  return (
    (typeof body.message === 'object' ? body.message.code : undefined) ??
    body.error?.code ??
    null
  );
}

export function memberDisplayName(member: {
  displayName?: string;
  email?: string;
}): string | null {
  return member.displayName?.trim() || member.email?.trim() || null;
}

export function memberInitials(member: { displayName?: string; email?: string }): string {
  const value = memberDisplayName(member) ?? '?';
  const words = value.split(/\s+/).filter(Boolean);
  return (words.length > 1 ? `${words[0][0]}${words[1][0]}` : value.slice(0, 2)).toUpperCase();
}
